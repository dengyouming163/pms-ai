import { pgTable, varchar, text, integer, timestamp, jsonb, uniqueIndex } from 'drizzle-orm/pg-core';
import { sql } from 'drizzle-orm';

// 订单表
export const pmsBuiOrders = pgTable('pms_bui_orders', {
  id: varchar('id', { length: 50 }).primaryKey(),
  merchantId: varchar('merchant_id', { length: 64 }).notNull().default('default'),
  orderNo: varchar('order_no', { length: 50 }).notNull().unique(),
  channel: varchar('channel', { length: 50 }).notNull(),
  channelColor: varchar('channel_color', { length: 20 }),
  icon: varchar('icon', { length: 20 }),
  channelOrderId: varchar('channel_order_id', { length: 50 }),
  guestName: varchar('guest_name', { length: 50 }).notNull(),
  guestPhone: varchar('guest_phone', { length: 20 }),
  guestId: varchar('guest_id', { length: 50 }),
  checkIn: varchar('check_in', { length: 20 }).notNull(),
  checkOut: varchar('check_out', { length: 20 }).notNull(),
  roomType: varchar('room_type', { length: 100 }),
  roomTypeId: varchar('room_type_id', { length: 50 }),
  roomNumber: varchar('room_number', { length: 20 }),
  roomId: varchar('room_id', { length: 50 }),
  nights: integer('nights').notNull().default(1),
  totalPrice: integer('total_price').notNull(),
  originalAmount: integer('original_amount'),
  discount: varchar('discount', { length: 100 }),
  extras: jsonb('extras'),
  source: varchar('source', { length: 30 }).default('ota'),
  paymentMethod: varchar('payment_method', { length: 30 }),
  paymentStatus: varchar('payment_status', { length: 20 }).default('unpaid'),
  status: varchar('status', { length: 30 }).notNull().default('pending_confirm'),
  remark: text('remark'),
  otaTimeout: timestamp('ota_timeout', { withTimezone: true }),
  otaOrderId: varchar('ota_order_id', { length: 100 }),
  platformOrderId: varchar('platform_order_id', { length: 50 }),
  platformOrderNo: varchar('platform_order_no', { length: 50 }),
  verifyCode: varchar('verify_code', { length: 6 }),
  confirmedAt: timestamp('confirmed_at', { withTimezone: true }),
  cancelledAt: timestamp('cancelled_at', { withTimezone: true }),
  cancelReason: text('cancel_reason'),
  storeId: varchar('store_id', { length: 50 }),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
}, (table) => [
  // 部分唯一索引：同一平台订单只生成一条住宿订单（转化幂等兜底，platform_order_id 为 NULL 不受约束）
  uniqueIndex('uq_orders_platform_order').on(table.platformOrderId).where(sql`${table.platformOrderId} IS NOT NULL`),
]);

