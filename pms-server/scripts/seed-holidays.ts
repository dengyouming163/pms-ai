// 幂等：按 date 补集写入（存在则跳过）。日期基于国务院 2026/2027 放假安排，
// 上线前须与官方公告逐条核对校准。
import { db } from '../src/db/index.js';
import { pmsBuiHolidays } from '../src/db/schema/index.js';
import { eq } from 'drizzle-orm';

// [date, name] —— 法定节假日当天（含补班日外的节日核心日；春节取除夕~初六黄金周）
const HOLIDAYS: Array<[string, string]> = [
  // 2026 年
  ['2026-01-01', '元旦'],
  ['2026-02-16', '春节'], ['2026-02-17', '春节'], ['2026-02-18', '春节'],
  ['2026-02-19', '春节'], ['2026-02-20', '春节'], ['2026-02-21', '春节'], ['2026-02-22', '春节'],
  ['2026-04-04', '清明'], ['2026-04-05', '清明'], ['2026-04-06', '清明'],
  ['2026-05-01', '劳动节'], ['2026-05-02', '劳动节'], ['2026-05-03', '劳动节'],
  ['2026-05-04', '劳动节'], ['2026-05-05', '劳动节'],
  ['2026-06-19', '端午'],
  ['2026-09-25', '中秋'],
  ['2026-10-01', '国庆'], ['2026-10-02', '国庆'], ['2026-10-03', '国庆'],
  ['2026-10-04', '国庆'], ['2026-10-05', '国庆'], ['2026-10-06', '国庆'], ['2026-10-07', '国庆'],
  // 2027 年（核心节日，日期按公告校准）
  ['2027-01-01', '元旦'],
  ['2027-02-06', '春节'], ['2027-02-07', '春节'], ['2027-02-08', '春节'],
  ['2027-02-09', '春节'], ['2027-02-10', '春节'], ['2027-02-11', '春节'], ['2027-02-12', '春节'],
  ['2027-04-04', '清明'], ['2027-04-05', '清明'], ['2027-04-06', '清明'],
  ['2027-05-01', '劳动节'], ['2027-05-02', '劳动节'], ['2027-05-03', '劳动节'],
  ['2027-05-04', '劳动节'], ['2027-05-05', '劳动节'],
  ['2027-06-09', '端午'],
  ['2027-09-15', '中秋'],
  ['2027-10-01', '国庆'], ['2027-10-02', '国庆'], ['2027-10-03', '国庆'],
  ['2027-10-04', '国庆'], ['2027-10-05', '国庆'], ['2027-10-06', '国庆'], ['2027-10-07', '国庆'],
];

async function main() {
  for (const [date, name] of HOLIDAYS) {
    const [exist] = await db.select({ id: pmsBuiHolidays.id }).from(pmsBuiHolidays)
      .where(eq(pmsBuiHolidays.date, date)).limit(1);
    if (!exist) {
      await db.insert(pmsBuiHolidays).values({ id: `hol_${date}`, date, name });
    }
  }
  console.log(`节假日种子同步完成：${HOLIDAYS.length} 条`);
  process.exit(0);
}

main().catch((e) => { console.error(e); process.exit(1); });
